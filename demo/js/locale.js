function lang(){
  const v = localeBag().lang;
  if (v === 'en' || v === 'zh-CN') return v;
  try { return localStorage.getItem('om_lang') === 'en' ? 'en' : 'zh-CN'; }
  catch (e) { return 'zh-CN'; }
}
function weekStart(){
  return localeBag().weekStart === 'sun' ? 'sun' : 'mon';
}
function tempUnit(){
  return localeBag().tempUnit === 'f' ? 'f' : 'c';
}
function tempC(v){
  const n = Number(v);
  if (!Number.isFinite(n)) return v;
  if (tempUnit() === 'f') return Math.round(n * 9 / 5 + 32);
  return Math.round(n);
}
function tempMark(){
  return tempUnit() === 'f' ? '°F' : '°C';
}
function enOf(src){
  if (src == null) return src;
  const m = String(src).match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!m || !m[2] || EN[m[2]] == null) return src;
  return m[1] + EN[m[2]] + m[3];
}
function t(s){
  if (s == null || lang() !== 'en') return s;
  return EN[s] == null ? s : EN[s];
}
function shown(src){
  return lang() === 'en' ? enOf(src) : src;
}
function skipEl(el){
  if (!el || el.nodeType !== 1) return true;
  if (el.closest(SKIP)) return true;
  return false;
}
function sourceText(node){
  const cur = node.nodeValue;
  const prev = textSrc.get(node);
  if (prev == null || (cur !== prev && cur !== enOf(prev))){
    textSrc.set(node, cur);
    return cur;
  }
  return prev;
}
